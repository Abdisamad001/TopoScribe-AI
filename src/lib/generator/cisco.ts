import { NetworkNode, Link, ProtocolConfig } from '@/types/network';

export function generateCiscoConfig(node: NetworkNode, allNodes: NetworkNode[], links: Link[], protocols: ProtocolConfig[]): string {
    const prompt = `${node.name}#`;
    let config = `${prompt} show running-config\n`;
    config += `Building configuration...\n\n`;

    config += `Current configuration : 1024 bytes\n`;
    config += `! Cisco IOS Configuration for ${node.name}\n`;
    config += `! Generated by TopoScribe AI\n!\n`;
    config += `version 15.1\n`;
    config += `no service timestamps log datetime msec\n`;
    config += `no service timestamps debug datetime msec\n`;
    config += `no service password-encryption\n`;
    config += `!\n`;
    config += `hostname ${node.name}\n`;
    config += `!\n`;
    config += `boot-start-marker\n`;
    config += `boot-end-marker\n`;
    config += `!\n`;

    // Interfaces
    node.interfaces.forEach(iface => {
        config += `interface ${iface.name}\n`;
        if (iface.ipAddress && iface.subnetMask) {
            config += ` ip address ${iface.ipAddress} ${iface.subnetMask}\n`;
        } else {
            config += ` no ip address\n`;
        }

        // Check if connected
        const isUp = links.some(l =>
            (l.sourceNodeId === node.id && (l.sourceInterfaceId === iface.id || !l.sourceInterfaceId)) ||
            (l.targetNodeId === node.id && (l.targetInterfaceId === iface.id || !l.targetInterfaceId))
        );

        if (!isUp) {
            config += ` shutdown\n`;
        } else {
            config += ` no shutdown\n`;
        }
        config += `!\n`;
    });

    // Routing Protocols (Simplified)
    const ospf = protocols.find(p => p.type === 'ospf' && p.enabled);
    if (ospf && node.type === 'router') {
        const pid = ospf.settings.processId || '1';
        const area = ospf.settings.area || '0';
        config += `router ospf ${pid}\n`;
        // Naive: advertise all connected networks
        node.interfaces.forEach(iface => {
            if (iface.ipAddress) {
                // Convert mask to wildcard (simplified)
                const wildcard = '0.0.0.0'; // TODO: calculate real wildcard
                // Actually we usually network x.x.x.x 0.0.0.0 area 0 for specific interface
                config += ` network ${iface.ipAddress} ${wildcard} area ${area}\n`;
            }
        });
        config += `!\n`;
    }

    config += `end\n\n`;
    config += `${prompt} write memory\n`;
    config += `Building configuration...\n`;
    config += `[OK]\n`;

    return config;
}
